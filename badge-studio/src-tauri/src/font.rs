/// Look up a glyph, falling back to '?' for unmapped characters.
pub fn glyph(c: char) -> Option<&'static [u8; 11]> {
    FONT.binary_search_by_key(&c, |(ch, _)| *ch)
        .ok()
        .map(|i| &FONT[i].1)
}

/// Render text into the column-major badge layout. One glyph is one byte column.
/// Returns the bitmap, the column count, and any characters with no glyph.
pub fn text_to_bitmap(text: &str) -> (Vec<u8>, usize, Vec<char>) {
    let fallback = glyph('?');
    let mut buf = Vec::new();
    let mut cols = 0usize;
    let mut missing = Vec::new();
    for c in text.chars() {
        let g = match glyph(c) {
            Some(g) => Some(g),
            None => {
                if !missing.contains(&c) {
                    missing.push(c);
                }
                fallback
            }
        };
        if let Some(g) = g {
            buf.extend_from_slice(g);
            cols += 1;
        }
    }
    (buf, cols, missing)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_is_sorted_for_binary_search() {
        assert!(
            FONT.windows(2).all(|w| w[0].0 < w[1].0),
            "FONT must be sorted and unique"
        );
    }

    #[test]
    fn renders_known_glyphs() {
        let (buf, cols, missing) = text_to_bitmap("HI");
        assert_eq!(cols, 2);
        assert_eq!(buf.len(), 22);
        assert!(missing.is_empty());
        // 'H' row 5 is the crossbar.
        assert_eq!(buf[5], 0xFE);
    }

    #[test]
    fn unmapped_chars_fall_back_and_are_reported() {
        let (_, cols, missing) = text_to_bitmap("A\u{5b57}");
        assert_eq!(cols, 2, "fallback still occupies a column");
        assert_eq!(missing, vec!['\u{5b57}']);
    }
}
